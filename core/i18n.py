"""Централізований словник перекладу: ключ -> (uk, en).
Мова зберігається в сесії; поточна мова доступна через contextvar (див. middleware)."""
from contextvars import ContextVar

DEFAULT = 'uk'
LANGS = ('uk', 'en')
_lang = ContextVar('lang', default=DEFAULT)


def set_lang(code):
    _lang.set(code if code in LANGS else DEFAULT)


def get_lang():
    return _lang.get()


def pick(uk, en):
    """Обрати значення за поточною мовою (для двомовних полів моделей)."""
    return uk if get_lang() == 'uk' else en


def tr(key, *args):
    pair = STRINGS.get(key)
    text = key if pair is None else pair[0 if get_lang() == 'uk' else 1]
    return text.format(*args) if args else text


